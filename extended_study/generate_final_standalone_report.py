def image_data_uri(path: Path) -> str | None:
    if not path.exists():
        return None
    mime = "image/png" if path.suffix.lower() == ".png" else "image/jpeg"
    data = base64.b64encode(path.read_bytes()).decode("ascii")
    return f"data:{mime};base64,{data}"


def html_escape(text: str) -> str:
    return (
        text.replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
    )


def rows(stats: Iterable[EventStat]) -> str:
    out = []
    for s in stats:
        drained = "" if s.drained_m3 is None else f"{s.drained_m3:,.0f}"
        note = ""
        if abs(s.pipe_peak_reduction_pct) < 0.05 and s.drained_m3:
            note = "全局最大值未降低；需结合体积/面积/P95指标解释"
        out.append(
            "<tr>"
            f"<td>{html_escape(s.event)}</td>"
            f"<td>{s.mike_peak_m:.3f}</td>"
            f"<td>{s.itzi_surface_peak_m:.3f}</td>"
            f"<td>{s.itzi_pipe_peak_m:.3f}</td>"
            f"<td>{s.surface_vs_mike_pct:.1f}%</td>"
            f"<td>{s.pipe_vs_mike_pct:.1f}%</td>"
            f"<td>{s.pipe_peak_reduction_pct:.1f}%</td>"
            f"<td>{drained}</td>"
            f"<td>{html_escape(note)}</td>"
            "</tr>"
        )
    return "\n".join(out)


def figure_sections() -> str:
    sections = []
    for title, path, caption in FIGURES:
        uri = image_data_uri(path)
        if uri is None:
            continue
        sections.append(
            "<section class='figure-section'>"
            f"<h3>{html_escape(title)}</h3>"
            f"<img src='{uri}' alt='{html_escape(title)}'>"
            f"<p class='caption'>{html_escape(caption)}</p>"
            f"<p class='path'>Source: {html_escape(str(path.relative_to(ROOT)))}</p>"
            "</section>"
        )
    return "\n".join(sections)


def csv_table_sections() -> str:
    sections = []
    for title, path, caption in TABLES:
        if not path.exists():
            continue
        with path.open("r", encoding="utf-8", newline="") as f:
            reader = csv.reader(f)
            data = list(reader)
        if not data:
            continue
        header, body = data[0], data[1:]
        head_html = "".join(f"<th>{html_escape(h)}</th>" for h in header)
        rows_html = []
        for row in body:
            cells = []
            for value in row:
                txt = html_escape(value)
                try:
                    num = float(value)
                    txt = f"{num:.3f}" if abs(num) < 1000 else f"{num:,.1f}"
                except ValueError:
                    pass
                cells.append(f"<td>{txt}</td>")
            rows_html.append("<tr>" + "".join(cells) + "</tr>")
        sections.append(
            "<section>"
            f"<h3>{html_escape(title)}</h3>"
            f"<p class='caption'>{html_escape(caption)}</p>"
            "<div class='table-wrap'><table>"
            f"<thead><tr>{head_html}</tr></thead>"
            f"<tbody>{''.join(rows_html)}</tbody>"
            "</table></div>"
            f"<p class='path'>Source: {html_escape(str(path.relative_to(ROOT)))}</p>"
            "</section>"
        )
    return "\n".join(sections)


