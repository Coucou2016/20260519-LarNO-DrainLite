@dataclass(frozen=True)
class EventStat:
    event: str
    mike_peak_m: float
    itzi_surface_peak_m: float
    itzi_pipe_peak_m: float
    drained_m3: float | None = None

    @property
    def surface_vs_mike_pct(self) -> float:
        return 100.0 * self.itzi_surface_peak_m / self.mike_peak_m

    @property
    def pipe_vs_mike_pct(self) -> float:
        return 100.0 * self.itzi_pipe_peak_m / self.mike_peak_m

    @property
    def pipe_peak_reduction_pct(self) -> float:
        if self.itzi_surface_peak_m == 0:
            return 0.0
        return 100.0 * (self.itzi_surface_peak_m - self.itzi_pipe_peak_m) / self.itzi_surface_peak_m


